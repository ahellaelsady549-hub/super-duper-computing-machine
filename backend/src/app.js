import express from 'express'; import cors from 'cors'; import helmet from 'helmet'; import rateLimit from 'express-rate-limit'; import authRoutes from './routes/authRoutes.js';
import productRoutes from './routes/productRoutes.js';
import orderRoutes from './routes/orderRoutes.js';
import customerRoutes from './routes/customerRoutes.js';
import groupOrderRoutes from './routes/groupOrderRoutes.js';
import quoteRoutes from './routes/quoteRoutes.js';
import adminRoutes from './routes/adminRoutes.js';
import engagementRoutes from './routes/engagementRoutes.js';
const app=express();
app.disable('x-powered-by');
app.set('trust proxy',1);
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
const allowedOrigins=(process.env.FRONTEND_URL||'http://localhost:5173').split(',').map(x=>x.trim()).filter(Boolean);
app.use(cors({origin:(origin,cb)=>{if(!origin||allowedOrigins.includes(origin))return cb(null,true);cb(new Error('CORS origin denied'));},credentials:false}));
app.use(express.json({limit:'1mb'}));
app.use(express.urlencoded({extended:false,limit:'1mb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:200,standardHeaders:true,legacyHeaders:false,message:{message:'Too many requests. Please try again later.'}})); app.get('/api/health',(req,res)=>res.json({ok:true,name:'REFLECT API'})); app.use('/api/auth',authRoutes);
app.use('/api/catalog',productRoutes);
app.use('/api/orders',orderRoutes);
app.use('/api/customer',customerRoutes);
app.use('/api/group-orders',groupOrderRoutes);
app.use('/api/quotes',quoteRoutes);
app.use('/api/admin',adminRoutes); app.use('/api/engagement',engagementRoutes);
app.use((req,res)=>res.status(404).json({message:'Endpoint not found'}));
app.use((err,req,res,next)=>{console.error(err);if(err.message==='CORS origin denied')return res.status(403).json({message:'Origin not allowed'});if(err.code==='LIMIT_FILE_SIZE')return res.status(413).json({message:'Uploaded file is too large'});res.status(err.status||500).json({message:err.status?err.message:'Server error'});}); export default app;
